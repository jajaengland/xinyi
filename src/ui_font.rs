const fn build() -> [u8; 4096] {
    let mut font = [0; 4096];
    let mut glyph = 0;
    // Symmetric column expansion keeps thin outer strokes and widens bowls.
    let columns = [0, 1, 1, 2, 3, 3, 4];
    let rows = [0, 0, 1, 2, 2, 3, 4, 4, 5, 6, 6];
    while glyph < 95 {
        let mut row = 0;
        while row < 11 {
            let source = GLYPHS[glyph][rows[row]];
            let mut bits = 0;
            let mut column = 0;
            while column < 7 {
                if source & (1 << (4 - columns[column])) != 0 {
                    bits |= 0x80 >> column;
                }
                column += 1;
            }
            font[(glyph + 32) * 16 + 2 + row] = bits;
            row += 1;
        }
        glyph += 1;
    }
    font
}
